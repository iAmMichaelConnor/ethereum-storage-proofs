const node = (b, B) =>
  `EncodedNode {bytes:${nr(pad(b, B))},length:${b.length},is_extension:${RLP.decode(b).length === 2}}`;
async function pathCase(name, values, hashed = false, expectedPayload = null) {
  const t = new Trie(),
    keys = values.map((_, i) => {
      const k = new Uint8Array(32);
      k[31] = i;
      return k;
    });
  for (let i = 0; i < values.length; i++)
    await t.put(keys[i], RLP.encode(values[i]));
  const proof = await t.createProof(keys[0]);
  assert.deepEqual(
    await t.verifyProof(t.root(), keys[0], proof),
    RLP.encode(values[0]),
  );
  const nodes = proof.slice(0, -1),
    B = Math.max(...nodes.map((n) => n.length));
  if (expectedPayload !== null) {
    const b = nodes.find((n) => RLP.decode(n).length === 17);
    assert.equal(
      b.length,
      expectedPayload +
        (expectedPayload <= 55 ? 1 : expectedPayload <= 255 ? 2 : 3),
    );
  }
  if (name === "reference_boundary_31")
    writeFileSync(
      "target/fixtures/completeness-paths.json",
      JSON.stringify(
        {
          capacity: B,
          root: limbs(t.root()),
          key: arr(keys[0]),
          value: { value: pad(values[0], 32), value_length: values[0].length },
          nodes: nodes.map((b) => ({
            bytes: pad(b, B),
            length: b.length,
            is_extension: RLP.decode(b).length === 2,
          })),
        },
        null,
        2,
      ) + "\n",
    );
  const body = `let (root,key,nodes,value)=unsafe {witness((${nr(limbs(t.root()))},${nr(keys[0])},[${nodes.map((b) => node(b, B)).join(",")}],${slot(values[0])}))};\n let cursor=verify_path_section(nodes,${nodes.length},new_cursor(root),key);verify_storage_leaf(cursor,key,value);`;
  test(name, body);
  if (hashed)
    test(
      name + "_hashed",
      body.replace("verify_path_section", "verify_hashed_path_section"),
    );
  return {
    leafBytes: proof.at(-1).length,
    branchBytes: nodes.find((n) => RLP.decode(n).length === 17).length,
  };
}
