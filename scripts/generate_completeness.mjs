const pad = (x, n) => [...x, ...Array(n - x.length).fill(0)];
const limbs = (x) =>
  Array.from({ length: 4 }, (_, i) =>
    arr(x.slice(8 * i, 8 * i + 8))
      .reduce((a, b, j) => a + (BigInt(b) << BigInt(8 * j)), 0n)
      .toString(),
  );
