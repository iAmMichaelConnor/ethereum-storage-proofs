// TXE fixtures of the example contracts, from independent EthereumJS tries in the witness
// format of scripts/witness. Nothing here is a real Ethereum state, contract or block.
// Run through scripts/generate.py.
import { Trie } from "@ethereumjs/trie";
import { RLP } from "@ethereumjs/rlp";
import { keccak256 } from "ethereum-cryptography/keccak.js";
import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { prepare } from "./witness/prepare.mjs";
import { prepareEvent } from "./witness/receipts.mjs";
import { receiptCases } from "./witness/receipt_cases.mjs";

const bytes = (values) => "[" + Array.from(values).join(", ") + "]";
const used = (n) => n.bytes.slice(0, n.length);
const nodeExpr = (n) => (n.length === 0 ? "empty_node()" : `node(${bytes(used(n))}, ${n.is_extension})`);
const PADDING = `
/// A proof node: \`prefix\` zero-padded to the node capacity.
fn node<let N: u32>(prefix: [u8; N], is_extension: bool) -> ProofNode {
    ProofNode { bytes: pad(prefix), length: N, is_extension }
}

/// An unused proof node.
fn empty_node() -> ProofNode {
    ProofNode { bytes: [0; 532], length: 0, is_extension: false }
}

/// \`prefix\` zero-padded to \`M\` bytes.
fn pad<let N: u32, let M: u32>(prefix: [u8; N]) -> [u8; M] {
    let mut out = [0; M];
    for i in 0..N {
        out[i] = prefix[i];
    }
    out
}
`;

// --- event_proof: logs of the receipt fixtures, in synthetic pinned blocks ---
{
  const NOW = 4000000000n, BLOCK_TIME = NOW - 120n, CHAIN_ID = 31337n;
  const cases = Object.fromEntries((await receiptCases()).map((c) => [c.name, c.input]));
  const capacity = { depth: 4, nodeBytes: 532, leafBytes: 1024, maxLogs: 3, dataBytes: 256 };
  async function log(name, doc, input, logIndex, number) {
    const { witness: w } = await prepareEvent(input, { ...capacity, logIndex });
    const e = w.expected;
    return `
/// ${doc}
pub fn ${name}() -> EthereumLog {
    EthereumLog {
        block: Block { chain_id: CHAIN_ID, number: ${number}, timestamp: BLOCK_TIME, receipts_root: ${bytes(Buffer.from(input.receiptsRoot.slice(2), "hex"))} },
        transaction_index: ${w.transaction_index},
        log_index: ${logIndex},
        nodes: [${w.nodes.map(nodeExpr).join(", ")}],
        count: ${w.count},
        leaf: pad(${bytes(w.leaf.slice(0, w.leaf_length))}),
        leaf_length: ${w.leaf_length},
        emitter: ${bytes(e.emitter)},
        topics: [${e.topics.map(bytes).join(", ")}],
        topic_count: ${e.topic_count},
        data: pad(${bytes(e.data.slice(0, e.data_length))}),
        data_length: ${e.data_length},
    }
}
`;
  }
  const text =
    "//! Generated by scripts/generate_example_fixtures.mjs. Do not edit.\n" +
    "//! Logs of independent EthereumJS receipt tries in synthetic pinned blocks; no chain has these blocks.\n" +
    "use event_proof_contract::{Block, EthereumLog, ProofNode};\n\n" +
    `/// The verifier time the block was pinned for.\npub global NOW: u64 = ${NOW};\n` +
    `/// The pinned block's time, two minutes before \`NOW\`.\npub global BLOCK_TIME: u64 = ${BLOCK_TIME};\n` +
    `/// A local development chain id.\npub global CHAIN_ID: u64 = ${CHAIN_ID};\n` +
    PADDING +
    (await log("transfer_log", "Log 1 of transaction 1 (a type-2 receipt): four topics and 56 data bytes, in block 100.", cases.typed_2, 1, 100)) +
    (await log("anonymous_log", "Log 0 of the same transaction: another emitter, no topics and no data.", cases.typed_2, 0, 100)) +
    (await log("historical_log", "Log 0 of a pre-Byzantium receipt (a post-state root, no status), in block 101.", cases.historical, 0, 101));
  writeFileSync("examples/event_proof/tests/src/fixture.nr", text);
}

// --- registry_gate: a synthetic registry with `mapping(bytes32 => uint256)` at slot 0 ---
{
  const word = (n) => Uint8Array.from(Buffer.from(BigInt(n).toString(16).padStart(64, "0"), "hex"));
  const minimal = (n) => {
    if (n === 0n) return new Uint8Array();
    let s = n.toString(16);
    if (s.length % 2) s = "0" + s;
    return Uint8Array.from(Buffer.from(s, "hex"));
  };
  const hex = (b) => "0x" + Buffer.from(b).toString("hex");
  const address = (byte) => Uint8Array.from(Array(20).fill(byte));
  const mappingKey = (key, slot) => keccak256(Uint8Array.from([...word(key), ...word(slot)]));
  const CHAIN_ID = 1n, REGISTRY = address(0x77), OTHER_REGISTRY = address(0x78);
  const A = 0xbe7n, B = 0xbe8n, VALUE_A = 2n, VALUE_A_LATER = 5n, VALUE_B = 1n;
  const CODE_HASH = keccak256(Buffer.from("synthetic registry code"));
  const storageTrie = async (entries) => {
    const trie = new Trie({ useKeyHashing: true });
    for (const [key, value] of entries) await trie.put(key, RLP.encode(minimal(value)));
    return trie;
  };
  // 48 filler accounts (so the account path has branch nodes), the registry with
  // entries for A and B, an entry for A at mapping slot 1 and 20 filler entries, and a
  // second registry with an entry for A.
  async function state(valueA) {
    const entries = [[mappingKey(A, 0n), valueA], [mappingKey(B, 0n), VALUE_B], [mappingKey(A, 1n), 3n]];
    for (let i = 1n; i <= 20n; i++) entries.push([mappingKey(0x1000n + i, 0n), 100n + i]);
    const registry = await storageTrie(entries);
    const other = await storageTrie([[mappingKey(A, 0n), 4n]]);
    const accounts = new Trie({ useKeyHashing: true });
    for (let i = 1; i <= 48; i++)
      await accounts.put(
        Uint8Array.from(keccak256(word(BigInt(i))).subarray(12)),
        RLP.encode([minimal(BigInt(i)), minimal(10n ** 18n * BigInt(i)), keccak256(RLP.encode(new Uint8Array())), keccak256(new Uint8Array())]),
      );
    for (const [account, trie] of [[REGISTRY, registry], [OTHER_REGISTRY, other]])
      await accounts.put(account, RLP.encode([minimal(1n), minimal(0n), trie.root(), CODE_HASH]));
    return { accounts, registry, other };
  }
  async function entry(name, doc, s, registry, trie, beneficiary, slot, value) {
    const key = mappingKey(beneficiary, slot);
    const w = await prepare(
      {
        stateRoot: hex(s.accounts.root()),
        proof: {
          address: hex(registry), nonce: "0x1", balance: "0x0", codeHash: hex(CODE_HASH), storageHash: hex(trie.root()),
          accountProof: (await s.accounts.createProof(registry)).map(hex),
          storageProof: [{ key: hex(key), value: "0x" + value.toString(16), proof: (await trie.createProof(key)).map(hex) }],
        },
      },
      { accountDepth: 8, accountBytes: 532, storageDepth: 6, storageBytes: 532 },
    );
    const a = w.account;
    assert(w.account_count > 1, "the account path should have branch nodes");
    return `
/// ${doc}
pub fn ${name}() -> RegistryEntry {
    RegistryEntry {
        chain: CHAIN_ID,
        state_root: ${bytes(s.accounts.root())},
        registry: ${bytes(registry)},
        mapping_slot: ${bytes(word(slot))},
        beneficiary: AztecAddress::from_field(0x${beneficiary.toString(16)}),
        account: RegistryAccount {
            nonce: ${bytes(a.nonce)},
            balance: ${bytes(a.balance)},
            nonce_length: ${a.nonce_length},
            balance_length: ${a.balance_length},
            storage_hash: [${a.storage_hash.join(", ")}],
            code_hash: [${a.code_hash.join(", ")}],
        },
        account_nodes: [${w.account_nodes.map(nodeExpr).join(", ")}],
        account_count: ${w.account_count},
        storage_nodes: [${w.storage_nodes.map(nodeExpr).join(", ")}],
        storage_count: ${w.storage_count},
        value: ${bytes(w.value.value)},
        value_length: ${w.value.value_length},
    }
}
`;
  }
  const now = await state(VALUE_A), later = await state(VALUE_A_LATER);
  const text =
    "//! Generated by scripts/generate_example_fixtures.mjs. Do not edit.\n" +
    "//! Account and storage proofs of a synthetic Ethereum state built with EthereumJS: a registry with\n" +
    "//! `mapping(bytes32 => uint256)` at slot 0 keyed by Aztec addresses. No chain has this state.\n" +
    "use aztec::protocol::{address::AztecAddress, traits::FromField};\n" +
    "use registry_gate_contract::{ProofNode, RegistryAccount, RegistryEntry};\n\n" +
    `pub global CHAIN_ID: Field = ${CHAIN_ID};\n` +
    `pub global STATE_ROOT: [u8; 32] = ${bytes(now.accounts.root())};\n` +
    `/// The state root after the registry raised beneficiary A's value to ${VALUE_A_LATER}.\n` +
    `pub global LATER_STATE_ROOT: [u8; 32] = ${bytes(later.accounts.root())};\n` +
    `pub global REGISTRY: [u8; 20] = ${bytes(REGISTRY)};\n` +
    `pub global OTHER_REGISTRY: [u8; 20] = ${bytes(OTHER_REGISTRY)};\n` +
    `pub global MAPPING_SLOT: [u8; 32] = [0; 32];\n` +
    `pub global BENEFICIARY_A: Field = 0x${A.toString(16)};\n` +
    `pub global BENEFICIARY_B: Field = 0x${B.toString(16)};\n` +
    `pub global VALUE_A: Field = ${VALUE_A};\n` +
    `pub global VALUE_A_LATER: Field = ${VALUE_A_LATER};\n` +
    `pub global VALUE_B: Field = ${VALUE_B};\n` +
    PADDING +
    (await entry("entry_a", "Beneficiary A's entry (value 2).", now, REGISTRY, now.registry, A, 0n, VALUE_A)) +
    (await entry("entry_b", "Beneficiary B's entry (value 1).", now, REGISTRY, now.registry, B, 0n, VALUE_B)) +
    (await entry("entry_a_slot_1", "Beneficiary A's entry at mapping slot 1 (value 3).", now, REGISTRY, now.registry, A, 1n, 3n)) +
    (await entry("entry_a_other_registry", "Beneficiary A's entry in the other registry (value 4).", now, OTHER_REGISTRY, now.other, A, 0n, 4n)) +
    (await entry("entry_a_later", "Beneficiary A's entry under the later state root (value 5).", later, REGISTRY, later.registry, A, 0n, VALUE_A_LATER));
  writeFileSync("examples/registry_gate/tests/src/fixture.nr", text);
}
