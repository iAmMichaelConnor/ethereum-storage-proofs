const joinBytes = (...parts) => Uint8Array.from(parts.flatMap(arr));
const mappingKey = (key, declaration) =>
  keccak256(joinBytes(key, word(declaration)));
const addressKey = (address, declaration) =>
  mappingKey(joinBytes(new Uint8Array(12), address), declaration);
const asInteger = (bytes) => BigInt("0x" + hex(bytes));
const arrayBase = keccak256(word(7));
const slotVectors = {
  MAPPING_ONE_SLOT_ZERO: mappingKey(word(1), 0),
  ADDRESS_001122_SLOT5: addressKey(
    Buffer.from("00112233445566778899aabbccddeeff00112233", "hex"),
    5,
  ),
  NESTED_1_2_SLOT5: keccak256(joinBytes(word(2), mappingKey(word(1), 5))),
  ARRAY_SLOT7_INDEX0_STRIDE1: arrayBase,
  ARRAY_SLOT7_INDEX2_STRIDE3: word(asInteger(arrayBase) + 2n * 3n),
  ARRAY_SLOT7_MAX_PRODUCT: word(
    asInteger(arrayBase) + ((1n << 32n) - 1n) ** 2n,
  ),
};
writeFileSync(
  "noir/ethereum_proofs/src/slot_key_vectors.nr",
  "// Generated by scripts/generate_fixtures.mjs using independent EthereumJS Keccak and integer arithmetic.\n" +
    Object.entries(slotVectors)
      .map(
        ([name, bytes]) =>
          `pub global ${name}: [u8; 32] = ${nrArr(arr(bytes))};\n`,
      )
      .join(""),
);

// Small offline EIP-1186-shaped proofs for the copyable balance examples.
// They are synthetic tries, not a claim about an Ethereum network or contract.
const exampleToken = Uint8Array.from(Array(20).fill(0x11));
const exampleHolder = Uint8Array.from(Array(20).fill(0x22));
const otherHolder = Uint8Array.from(Array(20).fill(0x33));
const exampleEntries = [
  [addressKey(exampleHolder, 9), 12345678901234567890n],
  [addressKey(otherHolder, 9), 42n],
  [addressKey(exampleHolder, 10), 999n],
];
const minimalInteger = (value) => {
  if (value === 0n) return new Uint8Array();
  let text = value.toString(16);
  if (text.length % 2) text = "0" + text;
  return Uint8Array.from(Buffer.from(text, "hex"));
};
async function balanceInput(entries, balance) {
  const exampleStorage = new Trie({ useKeyHashing: true });
  for (const [key, value] of entries)
    await exampleStorage.put(key, RLP.encode(minimalInteger(value)));
  const exampleState = new Trie({ useKeyHashing: true });
  const exampleCodeHash = keccak256(Uint8Array.of(0));
  const exampleNonce = 7n;
  const exampleBalance = balance;
  const exampleAccountRlp = RLP.encode([
    minimalInteger(exampleNonce),
    minimalInteger(exampleBalance),
    exampleStorage.root(),
    exampleCodeHash,
  ]);
  await exampleState.put(exampleToken, exampleAccountRlp);
  await exampleState.put(
    Uint8Array.from(Array(20).fill(0x99)),
    exampleAccountRlp,
  );
  return {
    stateRoot: "0x" + hex(exampleState.root()),
    proof: {
      address: "0x" + hex(exampleToken),
      nonce: "0x" + exampleNonce.toString(16),
      balance: "0x" + exampleBalance.toString(16),
      storageHash: "0x" + hex(exampleStorage.root()),
      codeHash: "0x" + hex(exampleCodeHash),
      accountProof: (await exampleState.createProof(exampleToken)).map(
        (bytes) => "0x" + hex(bytes),
      ),
      storageProof: await Promise.all(
        entries.map(async ([key, value]) => ({
          key: "0x" + hex(key),
          value: "0x" + value.toString(16),
          proof: (await exampleStorage.createProof(key)).map(
            (bytes) => "0x" + hex(bytes),
          ),
        })),
      ),
    },
  };
}
const exampleInput = await balanceInput(exampleEntries, 1000000000000000000n);
exampleInput.example = {
  kind: "synthetic",
  holder: arr(exampleHolder),
  other_holder: arr(otherHolder),
  balances_slot: 9,
  balance: exampleEntries[0][1].toString(),
};
// Both negative values have valid authenticated paths; only the requested cast
// is too narrow. The checker must reach the conversion guard, not a hash failure.
exampleInput.example.overflow_storage = await balanceInput(
  exampleEntries.map(([key, value], index) => [
    key,
    index === 0 ? 1n << 128n : value,
  ]),
  1000000000000000000n,
);
exampleInput.example.overflow_account = await balanceInput(
  exampleEntries,
  21888242871839275222246405745257275088548364400416034343698204186575808495617n,
);
writeFileSync(
  "target/fixtures/balance-examples.json",
  JSON.stringify(exampleInput, null, 2) + "\n",
);
console.log(
  "EthereumJS verified generated and upstream account/storage proofs; wrote Noir tests.",
);

