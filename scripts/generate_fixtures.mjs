function encodeOld(n) {
  if (Number(n.node_type) === 0)
    return RLP.encode([
      ...n.rows.map((r, i) => (n.row_exist[i] ? unlimbs(r) : new Uint8Array())),
      new Uint8Array(),
    ]);
  return RLP.encode([
    Uint8Array.from([
      Number(n.rows[0][0]) * 16 + Number(n.rows[0][1]),
      ...unlimbs(n.rows[1]).slice(0, Number(n.rows[0][2])),
    ]),
    unlimbs(n.rows[2]),
  ]);
}
function leaf(key, used, value) {
  let nibs = hex(key).slice(used);
  const hp = (nibs.length % 2 ? "3" : "20") + nibs;
  return RLP.encode([Uint8Array.from(Buffer.from(hp, "hex")), value]);
}
function makeProof(nodes, count, key, value) {
  const path = nodes.slice(0, Number(count)).map(encodeOld);
  let used = 0;
  for (const b of path) {
    const p = RLP.decode(b);
    used += p.length === 17 ? 1 : (p[0].length - 1) * 2 + (p[0][0] >> 4);
  }
  return [...path, leaf(key, used, value)];
}
