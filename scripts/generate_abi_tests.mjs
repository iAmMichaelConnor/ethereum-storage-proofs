// Real-witness tests of the producer shapes and consumer functions: valid openings from
// independent EthereumJS tries, each mutated field rejected, and padding in unused
// capacity accepted. Every input passes through std::hint::black_box, so the tests run
// the circuits on runtime witnesses rather than on folded constants. For absence, an
// independent EthereumJS lookup decides whether a mutated claim is still true, because
// a different absent key can correctly reuse the same terminal node.
// Run through scripts/generate.py.
