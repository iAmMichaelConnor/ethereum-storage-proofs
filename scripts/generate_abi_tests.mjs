const clone = (x) => structuredClone(x);
const hex = (b) => "0x" + Buffer.from(b).toString("hex");
const word = (n) =>
  Uint8Array.from(Buffer.from(BigInt(n).toString(16).padStart(64, "0"), "hex"));
const flip = (x, bit = 0) =>
  typeof x === "string" ? (BigInt(x) ^ (1n << BigInt(bit))).toString() : x ^ (1 << bit);

// JSON witness values to Noir literals. Struct types are recognised by their fields.
const STRUCTS = [
  ["EncodedNode", ["bytes", "length", "is_extension"]],
  ["StorageSlot", ["value", "value_length"]],
  ["IndexedPath", ["indices", "count"]],
  [
    "Account",
    ["address", "nonce", "nonce_length", "balance", "balance_length", "storage_hash", "code_hash"],
  ],
];
function nr(v) {
  if (Array.isArray(v)) return "[" + v.map(nr).join(", ") + "]";
  if (typeof v === "boolean") return String(v);
  if (typeof v === "number" || typeof v === "bigint") return String(v);
  if (typeof v === "string") {
    assert(/^[0-9]+$/.test(v), `not a decimal: ${v}`);
    return v;
  }
  const keys = Object.keys(v).sort();
  const match = STRUCTS.find(([, fields]) => [...fields].sort().join() === keys.join());
  assert(match, "unknown struct with fields " + keys.join());
  return `${match[0]} { ${match[1].map((k) => `${k}: ${nr(v[k])}`).join(", ")} }`;
}
const struct = (name, v, fields) =>
  `${name} { ${fields.map((k) => `${k}: ${nr(v[k])}`).join(", ")} }`;

// One test module: a function per witness, then tests that call a target with it,
// optionally after a mutation. `args` names the target's parameters in order.
class Module {
  constructor(header, uses) {
    this.text = header + uses + "use std::hint::black_box;\n";
    this.names = new Set();
  }
  witness(name, args, types, values) {
    name = "case_" + name;
    this.text += `\nfn ${name}() -> (${types.join(", ")}) {\n(${values.join(", ")})\n}\n`;
    return { name, args };
  }
  test(name, w, call, { mutate = "", fails, check = "" } = {}) {
    assert(!this.names.has(name), "duplicate test " + name);
    this.names.add(name);
    const attr = fails ? `#[test(should_fail_with = ${JSON.stringify(fails)})]` : "#[test]";
    const binding = mutate ? `let (${w.args.map((a) => "mut " + a).join(", ")})` : `let (${w.args.join(", ")})`;
    const mutation = mutate ? `\n${mutate}\nlet (${w.args.join(", ")}) = (${w.args.join(", ")});` : "";
    this.text +=
      `\n${attr}\nfn ${name}() {\n${binding} = ${w.name}();${mutation}\n` +
      `let (${w.args.join(", ")}) = black_box((${w.args.join(", ")}));\n` +
      `let result = ${call}(${w.args.join(", ")});\n${check || "let _ = result;"}\n}\n`;
  }
}

