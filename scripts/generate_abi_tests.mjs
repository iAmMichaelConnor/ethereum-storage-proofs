// --- Shared-node batches (ethereum_proofs::batch::verify_storage_batch) ---
async function batchEnvelope(t, keys, values) {
  const address = new Uint8Array(20).fill(0x42),
    code = keccak256(new Uint8Array()),
    accountValue = RLP.encode([Uint8Array.of(1), new Uint8Array(), t.root(), code]);
  const accounts = new Trie({ useKeyHashing: true });
  await accounts.put(address, accountValue);
  return {
    stateRoot: hex(accounts.root()),
    proof: {
      address: hex(address),
      nonce: "0x1",
      balance: "0x0",
      storageHash: hex(t.root()),
      codeHash: hex(code),
      accountProof: (await accounts.createProof(address)).map(hex),
      storageProof: await Promise.all(
        keys.map(async (k, i) => ({
          key: hex(k),
          value: hex(values[i]),
          proof: (await t.createProof(keccak256(k))).map(hex),
        })),
      ),
    },
  };
}
{
  const m = new Module(
    "// Generated by scripts/generate_abi_tests.mjs from independent EthereumJS tries. Do not edit.\n",
    "use crate::batch::{IndexedPath, verify_storage_batch};\nuse crate::proof::EncodedNode;\nuse crate::types::StorageSlot;\n",
  );
  const ARGS = ["root", "slot_keys", "values", "nodes", "node_count", "paths"];
  const batch = (name, w, k, p, d, b) =>
    m.witness(
      name,
      ARGS,
      ["[u64; 4]", `[[u8; 32]; ${k}]`, `[StorageSlot; ${k}]`, `[EncodedNode<${b}>; ${p}]`, "u32", `[IndexedPath<${d}>; ${k}]`],
      [w.root, w.slot_keys, w.values, w.nodes, w.node_count, w.paths].map(nr),
    );
  // Four keys in two groups of two that share their first nibble: three shared nodes.
  const groups = [[], []];
  for (let n = 0; groups.some((g) => g.length < 2); n++) {
    const k = word(n), h = keccak256(k), g = h[0] >> 4;
    if (g < 2 && groups[g].length < 2 && !groups[g].some((x) => (keccak256(x)[0] & 15) === (h[0] & 15)))
      groups[g].push(k);
  }
  const keys = groups.flat(),
    values = keys.map((_, i) => new Uint8Array(32).fill(i + 1)),
    trie = new Trie();
  for (let i = 0; i < keys.length; i++) await trie.put(keccak256(keys[i]), RLP.encode(values[i]));
  const shared = await prepareBatchStorage(await batchEnvelope(trie, keys, values), {
    slots: 4, nodeCapacity: 3, pathDepth: 2, nodeBytes: 135,
  });
  assert(shared.node_count === 3 && shared.paths.every((p) => p.count === 2));
  const s = batch("shared", shared, 4, 3, 2, 135);
  m.test("batch_shared_nodes", s, "verify_storage_batch");
  const rejections = [
    ["other_root", "root[0] ^= 1;", NODE_HASH],
    ["other_slot_key", "slot_keys[2][0] ^= 1;", "Missing child"],
    ["other_value", "values[3].value[0] ^= 1;", NODE_HASH],
    ["changed_node", "nodes[0].bytes[10] ^= 1;", NODE_HASH],
    ["changed_path", "paths[1].indices[1] = 0;", NODE_HASH],
    ["path_count_above_depth", "paths[0].count = 3;", "Path count exceeds capacity"],
    ["node_count_above_capacity", "node_count = 4;", "Node count exceeds capacity"],
    ["reference_to_unused_node", "node_count = 1;", "Path index outside active node table"],
    ["cycle", "paths[0].indices = [0, 0];", NODE_HASH],
    ["duplicate_key_with_other_value", "slot_keys[1] = slot_keys[0]; paths[1] = paths[0];", NODE_HASH],
  ];
  for (const [name, mutate, fails] of rejections)
    m.test("batch_rejects_" + name, s, "verify_storage_batch", { mutate, fails });
  m.test("batch_accepts_duplicate_keys", s, "verify_storage_batch", {
    mutate: "slot_keys[1] = slot_keys[0]; values[1] = values[0]; paths[1] = paths[0];",
  });
  m.test("batch_accepts_any_claim_order", s, "verify_storage_batch", {
    mutate:
      "slot_keys = [slot_keys[3], slot_keys[2], slot_keys[1], slot_keys[0]];\n" +
      "values = [values[3], values[2], values[1], values[0]];\n" +
      "paths = [paths[3], paths[2], paths[1], paths[0]];",
  });
  // Unused table entries and path indices may hold anything.
  const padded = clone(shared);
  padded.nodes.push({ bytes: Array(135).fill(255), length: 4294967295, is_extension: true });
  for (const p of padded.paths) p.indices.push(4294967295);
  m.test("batch_ignores_padding", batch("padded", padded, 4, 4, 3, 135), "verify_storage_batch");
  // Small values make embedded leaves; the same keys appear twice.
  const inline = new Trie(), ik = [word(0), word(1)], iv = [Uint8Array.of(1), Uint8Array.of(128)];
  for (let i = 0; i < 2; i++) {
    const h = keccak256(ik[i]);
    await inline.put(h, RLP.encode(iv[i]));
    const sibling = Uint8Array.from(h);
    sibling[31] ^= 1;
    await inline.put(sibling, RLP.encode(Uint8Array.of(2)));
  }
  const inlined = await prepareBatchStorage(
    await batchEnvelope(inline, [...ik, ...ik], [...iv, ...iv]),
    { slots: 4, nodeCapacity: 8, pathDepth: 5, nodeBytes: 135 },
  );
  m.test("batch_embedded_leaves_and_duplicates", batch("inline", inlined, 4, 8, 5, 135), "verify_storage_batch");
  writeFileSync("noir/ethereum_storage_proofs/src/batch_tests.nr", m.text);
}

