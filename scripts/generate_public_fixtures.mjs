const arr = (b) => Array.from(b);
const fromHex = (h) => Uint8Array.from(Buffer.from(h.slice(2), "hex"));
const hex = (b) => Buffer.from(b).toString("hex");
const word = (n) =>
  Uint8Array.from(Buffer.from(BigInt(n).toString(16).padStart(64, "0"), "hex"));
const lanes = (b) =>
  Array.from({ length: 4 }, (_, i) =>
    arr(b.slice(8 * i, 8 * i + 8)).reduce(
      (a, v, j) => a + (BigInt(v) << BigInt(8 * j)),
      0n,
    ),
  );
const pad32 = (b) => Uint8Array.from([...b, ...Array(32 - b.length).fill(0)]);
const three = (l, i) =>
  (l[i] ?? 0n) + ((l[i + 1] ?? 0n) << 64n) + ((l[i + 2] ?? 0n) << 128n);
const integer = (b) => (b.length ? BigInt("0x" + hex(b)) : 0n);
const halves = (n) => [n >> 128n, n & ((1n << 128n) - 1n)];

// The packed node layout of noir/ethereum_public_proofs/src/node.nr: RLP bytes
// as little-endian lanes, three per field, 23 fields.
function packNode(bytes) {
  assert(bytes.length < 544);
  const padded = Uint8Array.from([...bytes, ...Array(552 - bytes.length).fill(0)]);
  const l = Array.from({ length: 69 }, (_, i) => lanes(pad32(padded.slice(8 * i, 8 * i + 8)))[0]);
  return Array.from({ length: 23 }, (_, k) => three(l, 3 * k));
}
function packAccount({ address, nonce, balance, storage, code }) {
  const s = lanes(storage),
    c = lanes(code);
  return [
    integer(address),
    integer(nonce),
    ...halves(integer(balance)),
    three(s, 0),
    s[3],
    three(c, 0),
    c[3],
  ];
}

