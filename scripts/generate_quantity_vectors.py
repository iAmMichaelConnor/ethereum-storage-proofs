"""Independent Python integer oracle for canonical Ethereum quantity conversions.

Uses the BN254 scalar modulus, Python to_bytes and divmod (no Noir implementation
or field arithmetic). Run through scripts/generate.py, which formats the output and supports --check.
"""

from pathlib import Path

P = 21888242871839275222246405745257275088548364400416034343698204186575808495617
HALF = 1 << 128
VALUES = [
    0,
    255,
    (1 << 64) - 1,
    HALF - 1,
    HALF + 2,
    (1 << 248) - 1,
    (0x01000000000000000000000000000002 << 128) + 0x03000000000000000000000000000004,
    (1 << 256) - 1,
    ((P // HALF) - 1) * HALF + HALF - 1,
    P - 1,
]


def encoded(value):
    length = (value.bit_length() + 7) // 8
    data = value.to_bytes(length, "big") + bytes(32 - length)
    return "[" + ", ".join(str(b) for b in data) + "]", length


def source():
    lines = [
        "// Generated by scripts/generate_quantity_vectors.py; Python integer oracle.",
        "// Canonical minimal big-endian bytes; expected halves use divmod(value, 2**128).",
        "use super::{Account, StorageSlot};",
        "use std::hint::black_box;",
        "#[test]",
        "fn python_integer_reference_vectors() {",
    ]
    for value in VALUES:
        data, length = encoded(value)
        high, low = divmod(value, HALF)
        lines += [
            f"let slot = StorageSlot {{ value: black_box({data}), value_length: black_box({length}) }};",
            f"assert_eq(slot.to_u128_pair(), ({high}, {low}));",
            f"assert_eq(slot.is_zero(), {'true' if value == 0 else 'false'});",
        ]
        if value < HALF:
            lines += [f"assert_eq(slot.to_u128(), {value});"]
        if value < P:
            lines += [
                f"assert_eq(slot.to_field(), {value});",
                "let a = Account { balance: slot.value, balance_length: slot.value_length, nonce: [0; 8], nonce_length: 0, address: [0; 20], storage_hash: [0; 4], code_hash: [0; 4] };",
                f"assert_eq(a.balance_as_field(), {value});",
            ]
    lines += ["}"]
    for label, value in (
        ("modulus", P),
        ("modulus_plus_one", P + 1),
        ("max_256", (1 << 256) - 1),
    ):
        data, length = encoded(value)
        for method in ("slot", "account"):
            lines += [
                '#[test(should_fail_with = "quantity exceeds native Field")]',
                f"fn python_{label}_{method}_rejects() {{",
                f"let slot = StorageSlot {{ value: black_box({data}), value_length: black_box({length}) }};",
            ]
            if method == "slot":
                lines += ["let _ = slot.to_field();"]
            else:
                lines += [
                    "let a = Account { balance: slot.value, balance_length: slot.value_length, nonce: [0; 8], nonce_length: 0, address: [0; 20], storage_hash: [0; 4], code_hash: [0; 4] };",
                    "let _ = a.balance_as_field();",
                ]
            lines += ["}"]
    return "\n".join(lines) + "\n"


def main():
    path = Path(__file__).resolve().parents[1] / "noir/ethereum_types/src/reference_vectors.nr"
    path.write_text(source())


if __name__ == "__main__":
    main()
